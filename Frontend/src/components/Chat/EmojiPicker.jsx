export default function EmojiPicker({ onEmojiSelect, isVisible, onClose }) {
  const [selectedCategory, setSelectedCategory] = useState(0)

  if (!isVisible) return null

  return (
    <div className="absolute bottom-full left-0 mb-2 bg-white border border-gray-200 rounded-lg shadow-lg z-20 w-80">
      <div className="p-3 border-b border-gray-200">
        <div className="flex items-center justify-between">
          <h3 className="text-sm font-medium text-gray-700">Emoji</h3>
          <button
            onClick={onClose}
            className="text-gray-400 hover:text-gray-600 transition"
          >
            ✕
          </button>
        </div>
        
        {/* Category tabs */}
        <div className="flex gap-1 mt-2 overflow-x-auto">
          {emojiCategories.map((category, index) => (
            <button
              key={category.name}
              onClick={() => setSelectedCategory(index)}
              className={`px-2 py-1 text-xs rounded transition ${
                selectedCategory === index
                  ? 'bg-blue-100 text-blue-600'
                  : 'text-gray-500 hover:text-gray-700'
              }`}
            >
              {category.name}
            </button>
          ))}
        </div>
      </div>
      
      {/* Emoji grid */}
      <div className="p-3 max-h-64 overflow-y-auto">
        <div className="grid grid-cols-8 gap-1">
          {emojiCategories[selectedCategory].emojis.map((emoji, index) => (
            <button
              key={index}
              onClick={() => {
                onEmojiSelect(emoji)
                onClose()
              }}
              className="w-8 h-8 flex items-center justify-center text-lg hover:bg-gray-100 rounded transition"
            >
              {emoji}
            </button>
          ))}
        </div>
      </div>
    </div>
  )
}